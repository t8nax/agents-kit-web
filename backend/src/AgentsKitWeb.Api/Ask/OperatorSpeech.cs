namespace AgentsKitWeb.Api.Ask;

/// <summary>
/// Как Чудо-Юдо пишет оператору. Оператор код не читает, и через имена файлов, куски кода и внутренние имена
/// в ответе ему приходится продираться — задача B-324. Правило одно на все разговоры панели и разбор флоу для отчёта:
/// своё в каждом окне расходилось бы молча. Подробность по прямой просьбе оператора — его решение на B-324.
/// </summary>
public static class OperatorSpeech
{
    public const string Rule = """
        Оператор код не читает. Всё, что ты пишешь ему, пиши обычными словами: что изменится для него и что ему
        решить. Не называй в этом тексте файлы, папки и пути, не приводи куски кода и команды, не пиши внутренних
        имён — классов, функций, переменных, ключей и полей; говори о том, что за ними стоит для работы. Называть
        можно то, что оператор сам видит в панели или в своём трекере, так, как он это видит: этапы, сценарии,
        исполнителей, разделы и кнопки, номера записей бэклога, модель и инструменты исполнителя, статусы, метки
        и поля трекера.
        Файл или имя называй, только если оператор сам об этом просит. Блоки правок, которые разбирает панель,
        пишутся по своим правилам: это правило — о твоих словах оператору.
        """;
}
